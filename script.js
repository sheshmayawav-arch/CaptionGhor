    function createCard(category, text, index) {

        const id =
            category + "-" + index;


        const card =
            document.createElement("article");

        card.className =
            "caption-card dynamic-caption-card";
card.dataset.id = id;

        // Category

        const categoryTitle =
            document.createElement("div");

        categoryTitle.className =
            "caption-category";

        categoryTitle.textContent =
            data[category].name;


        // Caption

        const caption =
            document.createElement("p");

        caption.className =
            "caption-text";

        caption.textContent =
            text;


        // Actions

        const actions =
            document.createElement("div");

        actions.className =
            "caption-actions";


        // COPY

        const copy =
            document.createElement("button");

        copy.className =
            "copy-btn";

        copy.textContent =
            "📋 কপি";

        copy.addEventListener(
            "click",
            function () {
                copyText(text);
            }
        );


        // SHARE

        const share =
            document.createElement("button");

        share.className =
            "share-btn";

        share.textContent =
            "📤 শেয়ার";

        share.addEventListener(
            "click",
            function () {
                shareText(text);
            }
        );


        // FAVORITE

        const favorite =
            document.createElement("button");

        favorite.className =
            "favorite-btn";


        function updateFavoriteButton() {

            const list =
                getFavorites();

            if (list.includes(id)) {

                favorite.textContent =
                    "♥";

                favorite.classList.add(
                    "active"
                );

            } else {

                favorite.textContent =
                    "♡";

                favorite.classList.remove(
                    "active"
                );
            }
        }


        updateFavoriteButton();


        favorite.addEventListener(
            "click",
            function () {

                const list =
                    getFavorites();

                const position =
                    list.indexOf(id);


                if (position === -1) {

                    list.push(id);

                    saveFavorites(list);

                    updateFavoriteButton();

                    showMessage(
                        "❤️ Favorite-এ যোগ হয়েছে!"
                    );

                } else {

                    list.splice(
                        position,
                        1
                    );

                    saveFavorites(list);

                    updateFavoriteButton();

                    showMessage(
                        "💔 Favorite থেকে সরানো হয়েছে"
                    );
                }


                if (favoriteMode) {
                    render();
                }

            }
        );


        actions.appendChild(copy);
        actions.appendChild(share);
        actions.appendChild(favorite);


        card.appendChild(categoryTitle);
        card.appendChild(caption);
        card.appendChild(actions);


        captionSection.appendChild(card);
    }

