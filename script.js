    function render() {

        if (!captionSection) return;


        document
            .querySelectorAll(
                ".dynamic-caption-card"
            )
            .forEach(function (card) {
                card.remove();
            });


        const search =
            searchInput
                ? searchInput.value
                    .toLowerCase()
                    .trim()
                : "";


        let total = 0;


        Object.keys(data).forEach(function (category) {


            // Category filter

            if (
                currentCategory !== "all" &&
                currentCategory !== category
            ) {
                return;
            }


            data[category].captions.forEach(
                function (text, index) {


                    // Search

                    if (
                        search &&
                        !text
                            .toLowerCase()
                            .includes(search)
                    ) {
                        return;
                    }


                    // Favorite filter

                    if (favoriteMode) {

                        const id =
                            category +
                            "-" +
                            (index + 1);

                        if (
                            !getFavorites()
                                .includes(id)
                        ) {
                            return;
                        }
                    }


                    createCard(
                        category,
                        text,
                        index + 1
                    );

                    total++;

                }
            );

        });


        if (noResult) {

            noResult.style.display =
                total === 0
                    ? "block"
                    : "none";
        }
    }


